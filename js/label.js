// Single-stroke vector lettering, so piece labels can be cut/engraved as paths. Glyph grid: 4 wide x 6 tall, advance 5.
window.FTM = window.FTM || {};
(function () {
  const O = [[1, 0], [0, 1], [0, 5], [1, 6], [3, 6], [4, 5], [4, 1], [3, 0], [1, 0]];
  const P = [[0, 0], [0, 6], [3, 6], [4, 5], [4, 4], [3, 3], [0, 3]];
  const G = {
    A: [[[0, 0], [2, 6], [4, 0]], [[1, 2], [3, 2]]],
    B: [[[0, 0], [0, 6], [3, 6], [4, 5], [4, 4], [3, 3], [0, 3]], [[3, 3], [4, 2], [4, 1], [3, 0], [0, 0]]],
    C: [[[4, 5], [3, 6], [1, 6], [0, 5], [0, 1], [1, 0], [3, 0], [4, 1]]],
    D: [[[0, 0], [0, 6], [2, 6], [4, 4], [4, 2], [2, 0], [0, 0]]],
    E: [[[4, 6], [0, 6], [0, 0], [4, 0]], [[0, 3], [3, 3]]],
    F: [[[4, 6], [0, 6], [0, 0]], [[0, 3], [3, 3]]],
    G: [[[4, 5], [3, 6], [1, 6], [0, 5], [0, 1], [1, 0], [3, 0], [4, 1], [4, 3], [2, 3]]],
    H: [[[0, 0], [0, 6]], [[4, 0], [4, 6]], [[0, 3], [4, 3]]],
    I: [[[1, 6], [3, 6]], [[2, 6], [2, 0]], [[1, 0], [3, 0]]],
    J: [[[4, 6], [4, 1], [3, 0], [1, 0], [0, 1]]],
    K: [[[0, 0], [0, 6]], [[4, 6], [0, 3], [4, 0]]],
    L: [[[0, 6], [0, 0], [4, 0]]],
    M: [[[0, 0], [0, 6], [2, 3], [4, 6], [4, 0]]],
    N: [[[0, 0], [0, 6], [4, 0], [4, 6]]],
    O: [O],
    P: [P],
    Q: [O, [[2, 2], [4, 0]]],
    R: [P, [[2, 3], [4, 0]]],
    S: [[[4, 5], [3, 6], [1, 6], [0, 5], [0, 4], [1, 3], [3, 3], [4, 2], [4, 1], [3, 0], [1, 0], [0, 1]]],
    T: [[[0, 6], [4, 6]], [[2, 6], [2, 0]]],
    U: [[[0, 6], [0, 1], [1, 0], [3, 0], [4, 1], [4, 6]]],
    V: [[[0, 6], [2, 0], [4, 6]]],
    W: [[[0, 6], [1, 0], [2, 3], [3, 0], [4, 6]]],
    X: [[[0, 0], [4, 6]], [[0, 6], [4, 0]]],
    Y: [[[0, 6], [2, 3], [4, 6]], [[2, 3], [2, 0]]],
    Z: [[[0, 6], [4, 6], [0, 0], [4, 0]]],
    0: [O, [[1, 1], [3, 5]]],
    1: [[[1, 5], [2, 6], [2, 0]], [[1, 0], [3, 0]]],
    2: [[[0, 5], [1, 6], [3, 6], [4, 5], [4, 4], [0, 0], [4, 0]]],
    3: [[[0, 5], [1, 6], [3, 6], [4, 5], [4, 4], [3, 3], [1, 3]], [[3, 3], [4, 2], [4, 1], [3, 0], [1, 0], [0, 1]]],
    4: [[[3, 0], [3, 6], [0, 2], [4, 2]]],
    5: [[[4, 6], [0, 6], [0, 3], [3, 3], [4, 2], [4, 1], [3, 0], [1, 0], [0, 1]]],
    6: [[[4, 5], [3, 6], [1, 6], [0, 5], [0, 1], [1, 0], [3, 0], [4, 1], [4, 2], [3, 3], [0, 3]]],
    7: [[[0, 6], [4, 6], [1, 0]]],
    8: [[[1, 3], [0, 4], [0, 5], [1, 6], [3, 6], [4, 5], [4, 4], [3, 3], [1, 3], [0, 2], [0, 1], [1, 0], [3, 0], [4, 1], [4, 2], [3, 3]]],
    9: [[[0, 1], [1, 0], [3, 0], [4, 1], [4, 5], [3, 6], [1, 6], [0, 5], [0, 4], [1, 3], [4, 3]]],
  };

  // Lettering along the centre line between rails A and B (2D polylines, same length). Returns open paths on layer 'LABEL'.
  FTM.labelPaths = function (text, A, B) {
    const n = A.length, M = [], S = [0], W = [];
    for (let i = 0; i < n; i++) { M.push([(A[i][0] + B[i][0]) / 2, (A[i][1] + B[i][1]) / 2]); W.push(Math.hypot(A[i][0] - B[i][0], A[i][1] - B[i][1])); }
    for (let i = 1; i < n; i++) S.push(S[i - 1] + Math.hypot(M[i][0] - M[i - 1][0], M[i][1] - M[i - 1][1]));
    const total = S[n - 1], chars = text.toUpperCase().split('').filter(c => G[c]);
    if (!chars.length || total <= 0) return [];
    const wid = W.slice().sort((a, b) => a - b)[n >> 1];
    let h = 0.4 * wid;                                    // letter height
    const need = ch => (chars.length * 5 - 1) * ch / 6;   // text length for letter height ch
    if (need(h) > 0.6 * total) h = 0.6 * total * 6 / (chars.length * 5 - 1);
    const k = h / 6, s0 = Math.min(1.5 * h, 0.2 * total);
    const at = s => { // point + direction on the centre line
      let i = 1; while (i < n - 1 && S[i] < s) i++;
      const u = (s - S[i - 1]) / ((S[i] - S[i - 1]) || 1), dx = M[i][0] - M[i - 1][0], dy = M[i][1] - M[i - 1][1], l = Math.hypot(dx, dy) || 1;
      return { p: [M[i - 1][0] + dx * u, M[i - 1][1] + dy * u], d: [dx / l, dy / l] };
    };
    const out = [];
    chars.forEach((ch, c) => {
      const f = at(s0 + (c * 5 + 2) * k), cs = f.d[0], sn = f.d[1];
      for (const stroke of G[ch]) out.push({
        layer: 'LABEL', closed: false,
        pts: stroke.map(([gx, gy]) => { const x = (gx - 2) * k, y = (gy - 3) * k; return [f.p[0] + cs * x - sn * y, f.p[1] + sn * x + cs * y]; }),
      });
    });
    return out;
  };
})();
